# 表記ゆれ（画面の名前の付け方の違い）
ALIASES = {"52ガロン": ".52ガロン", "96ガロン": ".96ガロン", "96ガロンデコ": ".96ガロンデコ",
           "スプラシュータ": "スプラシューター", "スパッタリーヒュー": "スパッタリー・ヒュー",
           "クーゲルシュライバーヒュー": "クーゲルシュライバー・ヒュー", "スプラニューバーコラボ": "スプラマニューバーコラボ"}


def norm(name):
    n = (name or "").replace(" ", "").replace("　", "")
    return ALIASES.get(n, n)


def main_of(name):
    """(メインの名前, 種類, 射程)。分からなければ (None, None, None)。"""
    n = norm(name)
    best = None
    for base, cls, rng in MAINS:
        if n.startswith(base) and (best is None or len(base) > len(best[0])):
            best = (base, cls, rng)
    return best or (None, None, None)


def _overrides(store):
    try:
        with open(os.path.join(store.root, "weapon_info.json"), encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def set_override(store, name, field, value):
    """画面から直したブキの情報を残す。field: 種類/射程/サブ/スペシャル"""
    d = _overrides(store)
    e = d.setdefault(norm(name), {})
    if value:
        e[field] = value
    else:
        e.pop(field, None)
    p = os.path.join(store.root, "weapon_info.json")
    with open(p + ".tmp", "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1, sort_keys=True)
    os.replace(p + ".tmp", p)


class Info:
    """ブキの名前から、種類・射程・サブ・スペシャルを引く。"""

    def __init__(self, store=None):
        self.over = _overrides(store) if store is not None else {}

    def get(self, name):
        n = norm(name)
        base, cls, rng = main_of(n)
        sub, sp = KITS.get(n, (None, None))
        d = {"名前": n, "メイン": base, "種類": cls, "射程": rng, "サブ": sub, "スペシャル": sp}
        for k, v in self.over.get(n, {}).items():
            d[k] = v
        return d
